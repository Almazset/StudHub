BEGIN;
CREATE TABLE IF NOT EXISTS user_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    type VARCHAR(30) NOT NULL,
    event_key VARCHAR(160) NOT NULL,
    detail VARCHAR(240) NOT NULL,
    href VARCHAR(240) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT user_notification_dedupe UNIQUE (recipient_id, type, event_key)
);

CREATE INDEX IF NOT EXISTS user_notification_recent
    ON user_notifications(recipient_id, created_at, id);

CREATE TABLE IF NOT EXISTS notification_mutes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    type VARCHAR(30) NOT NULL,
    CONSTRAINT notification_mute_once UNIQUE (recipient_id, type)
);
COMMIT;
