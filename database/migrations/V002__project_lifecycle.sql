BEGIN;
ALTER TABLE study_projects ADD COLUMN IF NOT EXISTS closed boolean DEFAULT false;
UPDATE study_projects SET closed=false WHERE closed IS NULL;
CREATE TABLE IF NOT EXISTS study_project_invitations (
 project_id bigint NOT NULL REFERENCES study_projects(id), user_id bigint NOT NULL,
 UNIQUE(project_id,user_id)
);
CREATE TABLE IF NOT EXISTS study_project_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id bigint NOT NULL, actor_id bigint NOT NULL,
 occurred_at timestamptz NOT NULL, description varchar(500) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_project_event_history ON study_project_events(project_id,id);
COMMIT;
