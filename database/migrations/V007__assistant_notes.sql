BEGIN;
CREATE TABLE IF NOT EXISTS assistant_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(150) NOT NULL,
    body VARCHAR(18000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS assistant_notes_owner_created
    ON assistant_notes(owner_id, created_at, id);

CREATE TABLE IF NOT EXISTS assistant_note_terms (
    note_id BIGINT NOT NULL REFERENCES assistant_notes(id) ON DELETE CASCADE,
    term_order INTEGER NOT NULL CHECK (term_order >= 0 AND term_order < 20),
    term VARCHAR(100) NOT NULL,
    definition VARCHAR(500) NOT NULL,
    PRIMARY KEY (note_id, term_order)
);
COMMIT;
