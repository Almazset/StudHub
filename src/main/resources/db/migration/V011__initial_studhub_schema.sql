-- PostgreSQL schema after the manual migrations through V011.
-- Flyway runs this file on an empty database. Existing schemas are enrolled at version 11.

CREATE TABLE public.assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    completed boolean NOT NULL,
    description character varying(1500),
    due_date date NOT NULL,
    priority character varying(10),
    title character varying(150) NOT NULL,
    course_id bigint,
    student_id bigint,
    status character varying(20),
    CONSTRAINT assignments_priority_check CHECK (((priority)::text = ANY (ARRAY[('LOW'::character varying)::text, ('MEDIUM'::character varying)::text, ('HIGH'::character varying)::text])))
);

CREATE TABLE public.assistant_note_terms (
    note_id bigint NOT NULL,
    term_order integer NOT NULL,
    term character varying(100) NOT NULL,
    definition character varying(500) NOT NULL,
    CONSTRAINT assistant_note_terms_term_order_check CHECK (((term_order >= 0) AND (term_order < 20)))
);

CREATE TABLE public.assistant_notes (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    owner_id bigint NOT NULL,
    title character varying(150) NOT NULL,
    body character varying(18000) NOT NULL,
    created_at timestamp with time zone NOT NULL
);

CREATE TABLE public.chat_attachments (
    message_id bigint NOT NULL,
    name character varying(120) NOT NULL,
    media_type character varying(100) NOT NULL,
    size integer NOT NULL,
    data bytea NOT NULL,
    CONSTRAINT chat_attachments_check CHECK ((octet_length(data) = size)),
    CONSTRAINT chat_attachments_size_check CHECK (((size >= 1) AND (size <= 8388608)))
);

CREATE TABLE public.chat_favorites (
    message_id bigint NOT NULL,
    user_id bigint NOT NULL
);

CREATE TABLE public.chat_members (
    id character varying(60) NOT NULL,
    last_read bigint NOT NULL,
    room_id character varying(36) NOT NULL,
    user_id bigint NOT NULL
);

CREATE TABLE public.chat_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    client_id character varying(36) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    room_id character varying(36) NOT NULL,
    sender_id bigint NOT NULL,
    text character varying(4000) NOT NULL,
    edited_at timestamp(6) with time zone,
    reply_to_id bigint,
    forwarded boolean DEFAULT false NOT NULL,
    pinned boolean DEFAULT false NOT NULL
);

CREATE TABLE public.chat_reactions (
    message_id bigint NOT NULL,
    user_id bigint NOT NULL,
    emoji character varying(16) NOT NULL
);

CREATE TABLE public.chat_rooms (
    id character varying(36) NOT NULL,
    direct_key character varying(50),
    kind character varying(10) NOT NULL,
    name character varying(80) NOT NULL,
    owner_id bigint,
    updated_at timestamp(6) with time zone NOT NULL
);

CREATE TABLE public.course_lessons (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    course_id bigint NOT NULL,
    section_title character varying(120) NOT NULL,
    section_order integer NOT NULL,
    lesson_order integer NOT NULL,
    title character varying(150) NOT NULL,
    content character varying(20000) NOT NULL
);

CREATE TABLE public.courses (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    description character varying(1000),
    teacher_name character varying(80) NOT NULL,
    title character varying(120) NOT NULL,
    external_url character varying(2000),
    start_instructions character varying(2000),
    language character varying(80),
    access_info character varying(1000)
);

CREATE TABLE public.friend_presence_preferences (
    user_id bigint NOT NULL,
    status character varying(12) NOT NULL
);

CREATE TABLE public.friendships (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp(6) with time zone NOT NULL,
    high_user_id bigint NOT NULL,
    low_user_id bigint NOT NULL,
    requester_id bigint NOT NULL,
    status character varying(12) NOT NULL
);

CREATE TABLE public.lesson_progress (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    lesson_id bigint NOT NULL,
    completed boolean NOT NULL,
    last_viewed_at timestamp with time zone
);

CREATE TABLE public.news_posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    body character varying(12000) NOT NULL,
    category character varying(255) NOT NULL,
    event_date date,
    link character varying(2000),
    published_at timestamp(6) without time zone,
    title character varying(160) NOT NULL,
    published boolean,
    source_name character varying(120),
    source_date date,
    status character varying(16),
    CONSTRAINT news_posts_category_check CHECK (((category)::text = ANY (ARRAY[('COURSE'::character varying)::text, ('UPDATE'::character varying)::text, ('ANNOUNCEMENT'::character varying)::text, ('USEFUL'::character varying)::text]))),
    CONSTRAINT news_posts_status_check CHECK (((status)::text = ANY ((ARRAY['PLANNED'::character varying, 'IN_PROGRESS'::character varying, 'RELEASED'::character varying])::text[])))
);

CREATE TABLE public.notification_mutes (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    recipient_id bigint NOT NULL,
    type character varying(30) NOT NULL
);

CREATE TABLE public.project_tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    assignee_id bigint,
    due_date date,
    project_id bigint NOT NULL,
    status character varying(20) NOT NULL,
    title character varying(150) NOT NULL,
    priority character varying(10)
);

CREATE TABLE public.study_plan_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    owner_id bigint NOT NULL,
    title character varying(150) NOT NULL,
    planned_date date NOT NULL,
    minutes integer NOT NULL,
    description character varying(1000) NOT NULL,
    completed boolean NOT NULL,
    CONSTRAINT study_plan_items_minutes_check CHECK (((minutes >= 5) AND (minutes <= 720))),
    CONSTRAINT study_plan_items_planned_date_check CHECK (((planned_date >= '0001-01-01'::date) AND (planned_date <= '9999-12-31'::date)))
);

CREATE TABLE public.study_project_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    project_id bigint NOT NULL,
    actor_id bigint NOT NULL,
    occurred_at timestamp with time zone NOT NULL,
    description character varying(500) NOT NULL
);

CREATE TABLE public.study_project_invitations (
    project_id bigint NOT NULL,
    user_id bigint NOT NULL
);

CREATE TABLE public.study_project_members (
    project_id bigint NOT NULL,
    user_id bigint NOT NULL
);

CREATE TABLE public.study_projects (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    description character varying(1000) NOT NULL,
    owner_id bigint NOT NULL,
    title character varying(120) NOT NULL,
    closed boolean DEFAULT false
);

CREATE TABLE public.study_steps (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    completed boolean NOT NULL,
    course_id bigint NOT NULL,
    title character varying(150) NOT NULL,
    user_id bigint NOT NULL
);

CREATE TABLE public.support_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    closed boolean NOT NULL,
    created_at timestamp(6) with time zone,
    message character varying(2000) NOT NULL,
    owner_id bigint NOT NULL,
    subject character varying(120) NOT NULL
);

CREATE TABLE public.user_blocks (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    blocker_id bigint NOT NULL,
    blocked_id bigint NOT NULL,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT user_blocks_other_account CHECK ((blocker_id <> blocked_id))
);

CREATE TABLE public.user_notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    recipient_id bigint NOT NULL,
    type character varying(30) NOT NULL,
    event_key character varying(160) NOT NULL,
    detail character varying(240) NOT NULL,
    href character varying(240) NOT NULL,
    created_at timestamp with time zone NOT NULL,
    read_at timestamp with time zone
);

CREATE TABLE public.user_reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    reporter_id bigint NOT NULL,
    reported_id bigint NOT NULL,
    reason character varying(20) NOT NULL,
    details character varying(1000) NOT NULL,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT user_reports_other_account CHECK ((reporter_id <> reported_id)),
    CONSTRAINT user_reports_reason_check CHECK (((reason)::text = ANY (ARRAY[('SPAM'::character varying)::text, ('HARASSMENT'::character varying)::text, ('INAPPROPRIATE'::character varying)::text, ('OTHER'::character varying)::text])))
);

CREATE TABLE public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    email character varying(120) NOT NULL,
    font_size character varying(255),
    full_name character varying(80) NOT NULL,
    language character varying(255),
    last_otp_step bigint,
    nickname character varying(32),
    otp_failures integer DEFAULT 0 NOT NULL,
    otp_locked_until timestamp(6) with time zone,
    password character varying(100) NOT NULL,
    photo bytea,
    profile_visibility character varying(255),
    recovery_code_hashes character varying(2000),
    role character varying(20) NOT NULL,
    theme character varying(255),
    two_factor_secret character varying(255),
    direct_messages character varying(12) DEFAULT 'members'::character varying NOT NULL,
    presence_visibility character varying(12) DEFAULT 'friends'::character varying NOT NULL,
    CONSTRAINT users_direct_messages_check CHECK (((direct_messages)::text = ANY (ARRAY[('members'::character varying)::text, ('friends'::character varying)::text, ('nobody'::character varying)::text]))),
    CONSTRAINT users_presence_visibility_check CHECK (((presence_visibility)::text = ANY (ARRAY[('friends'::character varying)::text, ('private'::character varying)::text]))),
    CONSTRAINT users_role_check CHECK (((role)::text = ANY (ARRAY[('USER'::character varying)::text, ('ADMIN'::character varying)::text])))
);

