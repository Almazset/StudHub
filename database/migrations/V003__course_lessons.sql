BEGIN;
ALTER TABLE courses ADD COLUMN IF NOT EXISTS start_instructions varchar(2000);
ALTER TABLE courses ADD COLUMN IF NOT EXISTS language varchar(80);
ALTER TABLE courses ADD COLUMN IF NOT EXISTS access_info varchar(1000);
CREATE TABLE IF NOT EXISTS course_lessons (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id bigint NOT NULL,section_title varchar(120) NOT NULL,
 section_order integer NOT NULL,lesson_order integer NOT NULL,
 title varchar(150) NOT NULL,content varchar(20000) NOT NULL
);
CREATE INDEX IF NOT EXISTS course_lesson_order ON course_lessons(course_id,section_order,lesson_order);
CREATE TABLE IF NOT EXISTS lesson_progress (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL,lesson_id bigint NOT NULL REFERENCES course_lessons(id),
 completed boolean NOT NULL,last_viewed_at timestamptz,
 UNIQUE(user_id,lesson_id)
);
COMMIT;
