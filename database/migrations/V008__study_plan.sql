BEGIN;
CREATE TABLE IF NOT EXISTS study_plan_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(150) NOT NULL,
    planned_date DATE NOT NULL CHECK (planned_date BETWEEN DATE '0001-01-01' AND DATE '9999-12-31'),
    minutes INTEGER NOT NULL CHECK (minutes BETWEEN 5 AND 720),
    description VARCHAR(1000) NOT NULL,
    completed BOOLEAN NOT NULL
);

CREATE INDEX IF NOT EXISTS study_plan_owner_date
    ON study_plan_items(owner_id, planned_date, id);
COMMIT;
