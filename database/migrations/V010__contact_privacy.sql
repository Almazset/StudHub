BEGIN;

ALTER TABLE users ADD COLUMN IF NOT EXISTS direct_messages VARCHAR(12) NOT NULL DEFAULT 'members'
    CHECK (direct_messages IN ('members', 'friends', 'nobody'));
ALTER TABLE users ADD COLUMN IF NOT EXISTS presence_visibility VARCHAR(12) NOT NULL DEFAULT 'friends'
    CHECK (presence_visibility IN ('friends', 'private'));

CREATE TABLE IF NOT EXISTS user_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    blocked_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT user_blocks_once UNIQUE (blocker_id, blocked_id),
    CONSTRAINT user_blocks_other_account CHECK (blocker_id <> blocked_id)
);
CREATE INDEX IF NOT EXISTS user_blocks_blocked_idx ON user_blocks(blocked_id);

CREATE TABLE IF NOT EXISTS user_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reported_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reason VARCHAR(20) NOT NULL CHECK (reason IN ('SPAM', 'HARASSMENT', 'INAPPROPRIATE', 'OTHER')),
    details VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT user_reports_other_account CHECK (reporter_id <> reported_id)
);
CREATE INDEX IF NOT EXISTS user_reports_reporter_date_idx ON user_reports(reporter_id, created_at);

COMMIT;
